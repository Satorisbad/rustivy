//! `ivy-metal` — MSL emission for Apple GPUs.
//!
//! Note the project rule: this backend is compiled and unit-tested on the operator's
//! Mac, and it never runs a model there. MSL text out, tests in, no thermal load.
#![forbid(unsafe_code)]

use ivy_core::{Error, ErrorKind, Result};
use ivy_kernel::{BinaryOp, Emitter, Program, Stmt, Target};

#[derive(Debug, Clone, Copy, Default)]
pub struct MslEmitter;

impl Emitter for MslEmitter {
    fn target(&self) -> Target {
        Target::Msl
    }

    fn emit(&self, program: &Program) -> Result<String> {
        if !self.supports(program) {
            return Err(Error::new(
                ErrorKind::KernelUnsupported,
                format!("MSL emitter has no lowering for `{}` yet", program.name),
            )
            .with_hint("burst #1 covers float32 elementwise binary programs only"));
        }
        let op = program
            .body
            .iter()
            .find_map(|s| {
                if let Stmt::Bin { op, .. } = s {
                    Some(*op)
                } else {
                    None
                }
            })
            .ok_or_else(|| Error::new(ErrorKind::KernelUnsupported, "no binary op in program"))?;

        let mut out = String::new();
        out.push_str("// Generated by ivy-metal. Do not edit.\n");
        out.push_str("#include <metal_stdlib>\nusing namespace metal;\n\n");
        out.push_str(&format!("kernel void {}(", program.name));
        for (i, b) in program.buffers.iter().enumerate() {
            let sep = if i == 0 { "" } else { ", " };
            let qual = if b.kind == ivy_kernel::BufferKind::Output {
                "device float*"
            } else {
                "device const float*"
            };
            out.push_str(&format!("{sep}{qual} {} [[buffer({i})]]", b.name));
        }
        let next = program.buffers.len();
        out.push_str(&format!(", constant uint& n [[buffer({next})]],\n"));
        out.push_str("    uint i [[thread_position_in_grid]])\n{\n");
        out.push_str("    if (i >= n) { return; }\n");
        out.push_str(&format!("    out[i] = a[i] {} b[i];\n", msl_op(op)));
        out.push_str("}\n");
        Ok(out)
    }
}

fn msl_op(op: BinaryOp) -> &'static str {
    match op {
        BinaryOp::Add => "+",
        BinaryOp::Sub => "-",
        BinaryOp::Mul => "*",
        BinaryOp::Div => "/",
        BinaryOp::Max => "max",
        BinaryOp::Min => "min",
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use ivy_kernel::Scalar;

    #[test]
    fn emits_msl_kernel() {
        let p = Program::elementwise_binary("ivy_add", Scalar::F32, BinaryOp::Add);
        let msl = MslEmitter.emit(&p).expect("emit");
        assert!(msl.contains("kernel void ivy_add("));
        assert!(msl.contains("out[i] = a[i] + b[i];"));
    }
}
