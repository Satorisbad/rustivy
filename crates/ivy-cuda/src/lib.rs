//! `ivy-cuda` — emits PTX text from [`ivy_kernel::Program`].
//!
//! Burst #1 stops at text: a program in, PTX out, unit-tested. Loading it with the
//! driver API (via `cudarc`) is burst #2, and is the point where a real device
//! benchmark becomes possible.
#![forbid(unsafe_code)]

use ivy_core::{Error, ErrorKind, Result};
use ivy_kernel::{BinaryOp, Emitter, Program, Scalar, Stmt, Target};

/// PTX emitter for a specific SM architecture.
#[derive(Debug, Clone, Copy)]
pub struct PtxEmitter {
    pub sm: u16,
}

impl PtxEmitter {
    /// T4 — the free-tier target.
    pub const T4: PtxEmitter = PtxEmitter { sm: 75 };
    /// A100 — the ladder's 1B target.
    pub const A100: PtxEmitter = PtxEmitter { sm: 80 };
    /// L4 / 4090.
    pub const L4: PtxEmitter = PtxEmitter { sm: 89 };
    /// H100.
    pub const H100: PtxEmitter = PtxEmitter { sm: 90 };
}

impl Emitter for PtxEmitter {
    fn target(&self) -> Target {
        Target::Ptx { sm: self.sm }
    }

    fn emit(&self, program: &Program) -> Result<String> {
        if !self.supports(program) {
            return Err(Error::new(
                ErrorKind::KernelUnsupported,
                format!(
                    "PTX emitter has no lowering for program `{}` yet",
                    program.name
                ),
            )
            .with_hint("burst #1 covers float32 elementwise binary programs only"));
        }
        let scalar = program.buffers[0].scalar;
        let op = elementwise_op(program)?;

        let mut out = String::new();
        out.push_str("// Generated by ivy-cuda. Do not edit.\n");
        out.push_str(".version 8.0\n");
        out.push_str(&format!(".target sm_{}\n", self.sm));
        out.push_str(".address_size 64\n\n");
        out.push_str(&format!(".visible .entry {}(", program.name));
        for (i, b) in program.buffers.iter().enumerate() {
            let sep = if i == 0 { "" } else { ", " };
            out.push_str(&format!("{sep}.param .u64 %param_{}", b.name));
        }
        out.push_str(", .param .u64 %param_n)\n{\n");
        out.push_str("    .reg .b64 %rd<10>;\n");
        out.push_str("    .reg .b32 %r<8>;\n");
        out.push_str(&format!(".reg .{} %f<8>;\n", ptx_scalar(scalar)));
        out.push_str("    .reg .pred %p<2>;\n\n");
        for (i, b) in program.buffers.iter().enumerate() {
            out.push_str(&format!(
                "    ld.param.u64 %rd{}, [%param_{}];\n",
                i + 1,
                b.name
            ));
        }
        let nreg = program.buffers.len() + 1;
        out.push_str(&format!("    ld.param.u64 %rd{nreg}, [%param_n];\n\n"));
        out.push_str("    mov.u32 %r1, %ctaid.x;\n");
        out.push_str("    mov.u32 %r2, %ntid.x;\n");
        out.push_str("    mov.u32 %r3, %tid.x;\n");
        out.push_str("    mad.lo.s32 %r4, %r1, %r2, %r3;\n");
        out.push_str("    cvt.u64.u32 %rd6, %r4;\n");
        out.push_str("    setp.ge.u64 %p1, %rd6, ");
        out.push_str(&format!("%rd{nreg};\n"));
        out.push_str("    @%p1 bra $L_done;\n\n");
        out.push_str("    mul.wide.u32 %rd7, %r4, 4;\n");
        for i in 0..program.buffers.len() {
            out.push_str(&format!("    add.s64 %rd{}, %rd{}, %rd7;\n", i + 1, i + 1));
        }
        out.push('\n');
        let s = ptx_scalar(scalar);
        out.push_str(&format!("    ld.global.{s} %f1, [%rd1];\n"));
        out.push_str(&format!("    ld.global.{s} %f2, [%rd2];\n"));
        out.push_str(&format!("    {op} %f3, %f1, %f2;\n"));
        out.push_str(&format!("    st.global.{s} [%rd3], %f3;\n\n"));
        out.push_str("$L_done:\n    ret;\n}\n");
        Ok(out)
    }
}

fn ptx_scalar(s: Scalar) -> &'static str {
    match s {
        Scalar::F32 => "f32",
        Scalar::F16 => "f16",
        Scalar::Bf16 => "bf16",
        Scalar::I32 => "s32",
        Scalar::U32 => "u32",
        Scalar::Bool => "u8",
    }
}

/// PTX instruction for a float32 binary op.
fn float_op(op: BinaryOp) -> &'static str {
    match op {
        BinaryOp::Add => "add.f32",
        BinaryOp::Sub => "sub.f32",
        BinaryOp::Mul => "mul.f32",
        BinaryOp::Div => "div.rn.f32",
        BinaryOp::Max => "max.f32",
        BinaryOp::Min => "min.f32",
    }
}

fn elementwise_op(program: &Program) -> Result<&'static str> {
    for stmt in &program.body {
        if let Stmt::Bin { op, .. } = stmt {
            return Ok(float_op(*op));
        }
    }
    Err(Error::new(
        ErrorKind::KernelUnsupported,
        "program contains no binary elementwise instruction",
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use ivy_kernel::Program;

    #[test]
    fn emits_entry_and_instruction() {
        let p = Program::elementwise_binary("ivy_add_f32", Scalar::F32, BinaryOp::Add);
        let ptx = PtxEmitter::T4.emit(&p).expect("emit");
        assert!(ptx.contains(".entry ivy_add_f32"));
        assert!(ptx.contains(".target sm_75"));
        assert!(ptx.contains("add.f32 %f3, %f1, %f2;"));
        assert!(ptx.contains("$L_done:"));
    }

    #[test]
    fn refuses_what_it_cannot_lower() {
        let mut p = Program::elementwise_binary("x", Scalar::F32, BinaryOp::Mul);
        // Non-f32 buffers are outside burst #1's lowering surface.
        p.buffers[0].scalar = Scalar::Bool;
        assert!(PtxEmitter::H100.emit(&p).is_err());
    }
}
